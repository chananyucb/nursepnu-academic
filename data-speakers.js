/* Thai fiscal year from date string (1 Oct – 30 Sep)
   e.g. "31-ต.ค.-68" → 2569,  "12-พ.ย.-68" → 2569,  "16-17 มี.ค.-69" → 2569 */
window.getSpeakerFY = function(dateStr) {
  if (!dateStr) return null;
  const M = { 'ม.ค.':1,'ก.พ.':2,'มี.ค.':3,'เม.ย.':4,'พ.ค.':5,'มิ.ย.':6,
              'ก.ค.':7,'ส.ค.':8,'ก.ย.':9,'ต.ค.':10,'พ.ย.':11,'ธ.ค.':12 };
  let month = null;
  for (const [k,v] of Object.entries(M)) { if (dateStr.includes(k)) { month=v; break; } }
  const ym = dateStr.match(/[-.\s](\d{2})\s*$/);
  if (!ym || !month) return null;
  const year = parseInt(ym[1]) + 2500;
  return month >= 10 ? year + 1 : year; // Oct-Dec → next FY
};
